"""Compile the explicit, unverified T1 hypothesis from bounded parameters."""
import copy
import json
from pathlib import Path
import magnetics
from transformer_candidates import bounded

ROOT = Path(__file__).resolve().parent


def compile_model(document):
    if (document.get('format') != 'dac-monitor-t1-parameters-v1'
            or document.get('qualification') != 'hypothetical-numerical-model'
            or not document.get('rationale') or not document.get('source_pages')
            or document.get('historical_topology_verified') is not False):
        raise ValueError('T1 requires explicit hypothetical provenance')
    if len(document.get('windings', [])) != 4:
        raise ValueError('T1 hypothesis requires four winding sections')
    windings = []
    for winding in document['windings']:
        if set(winding) != {'turns', 'resistance_ohm', 'leakage_h', 'capacitance_f', 'polarity'}:
            raise ValueError('invalid T1 winding parameters')
        sign = winding['polarity']
        if type(sign) is not int or sign not in (-1, 1):
            raise ValueError('invalid T1 polarity')
        windings.append({k: bounded(v) for k, v in winding.items() if k != 'polarity'} | {'polarity': sign})
    core = copy.deepcopy(document['core'])
    for key in ('area_m2', 'length_m', 'loss_ohm'):
        core[key] = bounded(core[key])
    # Independently vary field and flux scales; retain oddness and monotonicity.
    core['h_a_per_m'] = [v * bounded(core['h_scale']) for v in core['h_a_per_m']]
    core['b_t'] = [v * bounded(core['b_scale']) for v in core['b_t']]
    return ('* Hypothetical T1; generated by converter_magnetics.py. No factory numerical data.\n'
            + magnetics.transformer_flux('T1_CORE', windings, core)
            + '.subckt T1_BOUND p12 collector t8 t7 ground t5\n'
            + 'Xcore p12 collector collector t8 p12 t7 ground t5 T1_CORE\n'
            + '.ends T1_BOUND\n')


if __name__ == '__main__':
    print(compile_model(json.loads((ROOT/'devices/t1-bound.json').read_text())), end='')
