#!/usr/bin/env python3
"""Generate the keyboard-only backend from the independently exercised candidates.

keyboard.c/h remain the immutable whole-clock reference used by older evidence.
Normal machine builds use keyboard_board.c/h; this generator owns their delta.
"""
import argparse
import re
import sys
import tempfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'verification/robotron-keyboard/digital'))
from cpu_bus_c import generate
from io_flags_candidate import replace_once


def outputs():
    files={}
    with tempfile.TemporaryDirectory() as tmp:
        folder=Path(tmp);generate(folder)
        for p in folder.glob('*.h'):
            text=p.read_text()
            text=re.sub(r'\bz80_\w+',lambda m:'k7658_'+m[0],text)
            if p.name!='candidate.h':text=re.sub(r'\bstatic (?!inline)','static inline ',text)
            files['generated/keyboard_cpu/'+p.name]=text
    header=(ROOT/'machines/robotron1715m/keyboard.h').read_text()
    header=header.replace('DAC_ROBOTRON_KEYBOARD_H','DAC_ROBOTRON_KEYBOARD_BOARD_H')
    header=replace_once(header,'#include "../../common/cpu/z80.h"','#include "keyboard_cpu.h"')
    header=replace_once(header,'  dac_z80 cpu;','  k7658_cpu cpu;\n  unsigned leds_known;')
    header=replace_once(header,'void robotron_keyboard_tick', 'void robotron_keyboard_reset(robotron_keyboard *);\nvoid robotron_keyboard_bus_request(robotron_keyboard *, int);\nvoid robotron_keyboard_tick')
    files['keyboard_board.h']='/* Generated by tools/generate_keyboard_cpu.py. */\n'+header
    text=(ROOT/'machines/robotron1715m/keyboard.c').read_text().replace('#include "keyboard.h"','#include "keyboard_board.h"')
    text=text.replace('dac_z80_init','k7658_cpu_init').replace('dac_z80_tick','k7658_cpu_tick')
    start=text.index('  /* The shared CPU presents')
    end=text.index('  uint8_t v =',start)
    text=text[:start]+'''  /* A4 stays transparent while selected. A6 clocks only on IORQ assertion. */
'''+text[end:]
    text=replace_once(text,'  k->leds = (a >> 13) & 3;\n  if (a & 0x8000)', '''  if (!(k->cpu.pins & Z80_IORQ)) {
    k->leds = (a >> 13) & 3;
    k->leds_known = 1;
  }
  if (a & 0x8000)''')
    text=replace_once(text,'  k->leds = (a >> 13) & 3;\n  serial_write', '  k->leds = (a >> 13) & 3;\n  k->leds_known = 1;\n  serial_write')
    text=replace_once(text,'static void output(void *p, uint16_t a, uint8_t v) {', '''static uint8_t acknowledge(void *p) {
  robotron_keyboard *k = p;
  if (!(k->cpu.pins & Z80_IORQ)) {
    k->leds = (Z80_GET_ADDR(k->cpu.controller.pins) >> 13) & 3;
    k->leds_known = 1;
  }
  return 0xff;
}
static void output(void *p, uint16_t a, uint8_t v) {''')
    if text.count('input, output, NULL')!=2:raise ValueError('Keyboard bus bindings changed')
    text=text.replace('input, output, NULL','input, output, acknowledge')
    text += '''
/* BR2 resets the CPU; neither the contacts nor A6 have a reset input. */
void robotron_keyboard_reset(robotron_keyboard *k) {
  k7658_cpu_reset(&k->cpu);
}
void robotron_keyboard_bus_request(robotron_keyboard *k, int asserted) {
  k->cpu.bus_request = !!asserted;
}
'''
    files['keyboard_board.c']='/* Generated by tools/generate_keyboard_cpu.py. */\n'+text
    return files


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
    for name,text in outputs().items():
        path=ROOT/'machines/robotron1715m'/name
        if a.check:
            if not path.is_file() or path.read_text()!=text:raise SystemExit('Generated keyboard source differs: '+name)
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)

if __name__=='__main__':main()
