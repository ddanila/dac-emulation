/* Held bus strobes must not advance the selector twice. Refresh/M1 reset
 * the sequence, and DMA routing is independent of a paused CPU cycle. */
static void bus_edges(void) {
 robotron_init(&m);
 for(unsigned b=1;b<=4;b++) for(unsigned pg=0;pg<16;pg++)
  m.prom[128+b*16+pg]=(pg>=12?1:1u<<(b-1))^15;
 m.bank=0x21;
 void (*pins)(void *,uint64_t)=m.cpu.observe_pins;
 pins(&m,Z80_M1|Z80_MREQ|Z80_RD);
 pins(&m,Z80_MREQ|Z80_RFSH);
 pins(&m,0);
 pins(&m,Z80_MREQ|Z80_RD);
 assert((robotron_mapping(&m,0x4000,0)&0xffffff)==0x4000);
 for(unsigned t=0;t<8;t++) {
  pins(&m,Z80_MREQ|Z80_RD|Z80_WAIT);
  assert((robotron_mapping(&m,0x4000,0)&0xffffff)==0x4000);
 }
 pins(&m,0);
 pins(&m,Z80_MREQ|Z80_WR);
 assert((robotron_mapping(&m,0x4000,1)&0xffffff)==0x14000);
 m.trace_master=DAC_MASTER_DMA;
 assert((robotron_mapping(&m,0x4000,0)&0xffffff)==0x4000);
 assert((robotron_mapping(&m,0x4000,1)&0xffffff)==0x14000);
 m.trace_master=DAC_MASTER_CPU;
 pins(&m,0);
 pins(&m,Z80_M1|Z80_MREQ|Z80_RD);
 pins(&m,0);
 pins(&m,Z80_MREQ|Z80_WR);
 assert((robotron_mapping(&m,0x4000,1)&0xffffff)==0x4000);
 /* Rebinding restores the callback, retaining emulated phase state. */
 m.cpu.observe_pins=NULL;
 robotron_rebind(&m);
 assert(m.cpu.observe_pins && m.bank_next_destination==1);
}
int main(void) {
 bus_edges();
 for (unsigned n=0;n<sizeof(cases)/sizeof(cases[0]);n++) {
  robotron_init(&m);
  for(unsigned b=1;b<=4;b++) for(unsigned pg=0;pg<16;pg++)
   m.prom[128+b*16+pg]=(pg>=12?1:1u<<(b-1))^15;
  m.ram[0x4000]=m.ram[0x4001]=0x11;
  m.ram[0x14000]=m.ram[0x14001]=0x22;
  m.ram[0xf060]=0x5a;
  const unsigned char setup[]={0x31,0x00,0xf7,0x21,0x00,0x40,
   0x11,0x60,0xf0,0xdd,0x21,0x00,0x40,0x01,0x01,0x00,
   0x3e,0x21,0xd3,0x24,0x3e,0x5a};
  memcpy(m.ram+0xf800,setup,sizeof(setup));
  memcpy(m.ram+0xf800+sizeof(setup),cases[n].code,cases[n].size);
  m.ram[0xf800+sizeof(setup)+cases[n].size]=0x76;
  m.cpu.pins=z80_prefetch(&m.cpu.cpu,0xf800);
  unsigned ticks=0;
  while(!(m.cpu.pins & Z80_HALT) && ticks++<2000) dac_z80_tick(&m.cpu,0,0);
  assert(ticks<2000);
  const unsigned char actual[]={m.ram[0x4000],m.ram[0x4001],
   m.ram[0x14000],m.ram[0x14001],m.cpu.cpu.l,m.cpu.cpu.h,m.cpu.cpu.a};
  if(memcmp(actual,cases[n].expected,sizeof(actual))) {
   fprintf(stderr,"bank-bus %s mismatch:",cases[n].name);
   for(unsigned i=0;i<sizeof(actual);i++) fprintf(stderr," %02x/%02x",actual[i],cases[n].expected[i]);
   fputc('\n',stderr);return 1;
  }
 }
 puts("Robotron bank bus: 20 physical instruction cases PASS");
 return 0;
}
