#!/usr/bin/env python3
from pathlib import Path
code=bytearray();labels={};fix=[]
def emit(*b):code.extend(b)
def label(n):labels[n]=0x100+len(code)
def ref(op,n):emit(op,0,0);fix.append((len(code)-2,n))
def call(n):ref(0xcd,n)
def jump(n):ref(0xc3,n)
def ld_a(v):emit(0x3e,v)
def out(p,v):ld_a(v);emit(0xd3,p)
def bdos(n):emit(0x0e,n,0x11,0x5c,0,0xcd,5,0)
# Original MIT CP/M XMODEM-128/checksum sender. DACTX NAME.EXT.
emit(0x3a,0x5d,0,0xfe,32);ref(0xca,'exit')
bdos(15);emit(0xfe,255);ref(0xca,'exit')
for v in [0x18,4,0x44,3,0xc1,5,0xea]:out(15,v)
out(9,7);out(9,13)
label('start');call('get');ref(0xda,'start');emit(0xfe,24);ref(0xca,'close');emit(0xfe,21);ref(0xc2,'start')
label('read');ref(0x11,'data');emit(0x0e,26,0xcd,5,0);bdos(20);emit(0xb7);ref(0xc2,'eot')
ld_a(10);ref(0x32,'retries')
label('packet');ld_a(1);call('put');ref(0x3a,'number');call('put');emit(0x2f);call('put')
ref(0x21,'data');emit(0x06,128,0x0e,0)
label('bytes');emit(0x7e);call('put');emit(0x81,0x4f,0x23,0x10,0);code[-1]=(labels['bytes']-(0x100+len(code)))&255
emit(0x79);call('put');call('get');ref(0xda,'retry');emit(0xfe,24);ref(0xca,'close');emit(0xfe,6);ref(0xc2,'retry')
ref(0x21,'number');emit(0x34);jump('read')
label('retry');ref(0x21,'retries');emit(0x35);ref(0xc2,'packet');ld_a(24);call('put');jump('close')
label('eot');ld_a(10);ref(0x32,'retries')
label('endtry');ld_a(4);call('put');call('get');ref(0xda,'endretry');emit(0xfe,6);ref(0xca,'close');emit(0xfe,24);ref(0xca,'close')
label('endretry');ref(0x21,'retries');emit(0x35);ref(0xc2,'endtry')
label('close');bdos(16)
label('exit');emit(0x11,0x80,0,0x0e,26,0xcd,5,0,0xc3,0,0)
label('get');emit(0xc5,0x01,0,0)
label('poll');emit(0xdb,15,0xe6,1);ref(0xc2,'received');emit(0x0b,0x78,0xb1);ref(0xc2,'poll');emit(0xc1,0x37,0xc9)
label('received');emit(0xdb,13,0xb7,0xc1,0xc9)
label('put');emit(0xf5)
label('txwait');emit(0xdb,15,0xe6,4);ref(0xca,'txwait');emit(0xf1,0xd3,13,0xc9)
label('number');emit(1)
label('retries');emit(10)
label('data');emit(*([0]*128))
for pos,name in fix:code[pos:pos+2]=labels[name].to_bytes(2,'little')
Path(__file__).with_name('DACTX.COM').write_bytes(code)
print(f'DACTX.COM: {len(code)} bytes')
